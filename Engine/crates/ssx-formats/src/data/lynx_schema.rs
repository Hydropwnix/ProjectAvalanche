#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum ParamType {
    Bool = 2,
    Int = 3,
    Float = 4,
    Reference = 5,
    Vector2 = 6,
    Vector3 = 7,
    Vector4 = 8,
    Matrix33 = 9,
    Matrix44 = 10,
    String64 = 11,
}

impl ParamType {
    pub fn from_name(name: &str) -> Option<ParamType> {
        let b = name.as_bytes();
        Some(match b.first()? {
            b'b' => ParamType::Bool,
            b'i' => ParamType::Int,
            b'f' => ParamType::Float,
            b'r' => ParamType::Reference,
            b's' => ParamType::String64,
            b'x' => ParamType::Matrix44,
            b'v' => match b.get(1) {
                Some(b'2') => ParamType::Vector2,
                Some(b'3') => ParamType::Vector3,
                _ => ParamType::Vector4,
            },
            _ => return None,
        })
    }
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub enum ParamDefault {
    Bool(bool),
    Int(i32),
    Float(f32),
    Vector([f32; 4]),
    None,
}

#[derive(Clone, Copy, Debug)]
pub struct ParamSchema {
    pub name: &'static str,
    pub ty: ParamType,
    pub max_count: u32,
    pub default: ParamDefault,
    pub field: u16,
}

#[derive(Clone, Copy, Debug)]
pub struct ClassSchema {
    pub name: &'static str,
    pub vtable: Option<u32>,
    pub param_def: u32,
    pub params: &'static [ParamSchema],
}

impl ClassSchema {
    pub fn param(&self, name: &str) -> Option<&'static ParamSchema> {
        self.params.iter().find(|p| p.name == name)
    }
}

pub fn class(name: &str) -> Option<&'static ClassSchema> {
    CLASSES.iter().find(|c| c.name == name)
}

